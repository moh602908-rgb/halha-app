/* ============================================================
   lib/config.js — الإعدادات المركزية لكل النظام
   ============================================================
   قاعدة واحدة صارمة: أي رقم أو اسم نموذج يُستخدم في أكثر من مكان يجب
   أن يُعرَّف هنا فقط، لا يُكتب مباشرة (Hardcoded) داخل أي ملف آخر.
   لتغيير الحد اليومي أو النموذج، غيّر القيمة هنا أو عبر متغير بيئة في
   Vercel — لا حاجة لتعديل أي منطق في أي ملف آخر بالمشروع.

   ملاحظة توافق النشر: هذا الملف لا يستورد أي شيء خاص بـ Vercel، فقط
   process.env القياسي في Node/Edge. هذا يعني أن طبقة الإعدادات بأكملها
   قابلة للنقل لأي استضافة أخرى (Cloudflare Workers, Netlify, AWS
   Lambda...) بأقل تعديل ممكن إن تغيّرت طريقة النشر مستقبلاً.
   ============================================================ */

function envInt(name, fallback) {
  const v = parseInt(process.env[name] || "", 10);
  return Number.isFinite(v) && v > 0 ? v : fallback;
}
function envStr(name, fallback) {
  const v = process.env[name];
  return (typeof v === "string" && v.trim()) ? v.trim() : fallback;
}

